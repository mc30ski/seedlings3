/**
 * Emit the SQL that brings a database's starter roles up to whatever
 * `install-starter-roles.ts` currently declares.
 *
 * WHY THIS EXISTS. Production is many policy revisions behind, and the
 * 2026-10-12 conversion migration created the roles as they stood THEN.
 * By 2026-10-26 six of the eight disagreed with the script — Super was
 * short twelve capabilities, Admin held four that had moved up to Super,
 * and Trainee had a `reports.view` that policy removed. Running the
 * installer by hand after `migrate deploy` would fix that, but it is a
 * second step somebody has to remember during a maintenance window.
 *
 * So the catch-up ships as a migration instead — and is GENERATED from
 * `ALL_STARTER_ROLES` rather than hand-copied, because hand-copying is
 * exactly what produced the drift in the first place. A generator cannot
 * disagree with its own input.
 *
 * WHAT IT DOES NOT DO. It never deletes a role, never touches a GRANT, and
 * never overwrites a Setting that already exists. A role an operator made
 * themselves is not in this set and is not referenced by it.
 *
 *   npx tsx scripts/generate-starter-roles-migration.ts          # print
 *   npx tsx scripts/generate-starter-roles-migration.ts --write  # to a file
 *
 * The output is deterministic, so re-running it on an unchanged script
 * produces byte-identical SQL — which is what lets a build gate compare
 * the shipped migration against the current definitions.
 */
import { writeFileSync, mkdirSync } from "node:fs";
import { join } from "node:path";
import { ALL_STARTER_ROLES, type StarterRole } from "./install-starter-roles";

/** Single-quote a SQL string literal. */
const q = (v: string) => `'${v.replace(/'/g, "''")}'`;
/** A key lookup, used wherever an id is needed. */
const idOf = (key: string) => `(SELECT id FROM "CustomRole" WHERE key = ${q(key)})`;

function roleSql(r: StarterRole): string {
  const out: string[] = [];
  out.push(`-- ── ${r.name} ──`);

  // ADOPT A SAME-NAMED KEYLESS ROLE, exactly as the installer does. An
  // operator may have created "Admin" by hand before keys existed; taking
  // it over preserves its id, and therefore every grant pointing at it.
  out.push(
    `UPDATE "CustomRole" SET key = ${q(r.key)}\n` +
      ` WHERE name = ${q(r.name)} AND key IS NULL;`,
  );

  const inherits = r.inheritsKey ? idOf(r.inheritsKey) : "NULL";
  const isPerspective = r.perspectiveOrder !== undefined;
  out.push(
    `INSERT INTO "CustomRole" (id, key, name, description, "isSystem", "isLadderRung", "isPerspective", "perspectiveOrder", "perspectiveIcon", "inheritsFromId", "createdAt")\n` +
      `VALUES (gen_random_uuid()::text, ${q(r.key)}, ${q(r.name)}, ${q(r.description)}, true, ${r.ladderRung ? "true" : "false"}, ${isPerspective}, ${r.perspectiveOrder ?? "NULL"}, ${r.perspectiveIcon ? q(r.perspectiveIcon) : "NULL"}, ${inherits}, now())\n` +
      `ON CONFLICT (key) DO UPDATE\n` +
      // Name and description are NOT re-asserted: an operator may have
      // renamed a role to their own vocabulary and that is theirs to keep.
      // Everything below is structure, which the app reasons about.
      `  SET "isSystem" = true,\n` +
      `      "isLadderRung" = ${r.ladderRung ? "true" : "false"},\n` +
      `      "isPerspective" = ${isPerspective},\n` +
      `      "perspectiveOrder" = ${r.perspectiveOrder ?? "NULL"},\n` +
      `      "perspectiveIcon" = ${r.perspectiveIcon ? q(r.perspectiveIcon) : "NULL"},\n` +
      `      "inheritsFromId" = ${inherits};`,
  );

  // THE ENTITLEMENT SET IS REPLACED, not merged. A stale one left behind is
  // policy nobody wrote — and this is the half that had drifted furthest.
  const list = [...r.adds].sort();
  if (list.length > 0) {
    out.push(
      `DELETE FROM "RoleEntitlement"\n` +
        ` WHERE "customRoleId" = ${idOf(r.key)}\n` +
        `   AND entitlement NOT IN (${list.map(q).join(", ")});`,
    );
    out.push(
      `INSERT INTO "RoleEntitlement" (id, "customRoleId", entitlement)\n` +
        `SELECT gen_random_uuid()::text, ${idOf(r.key)}, e\n` +
        `  FROM unnest(ARRAY[${list.map(q).join(", ")}]) AS e\n` +
        `ON CONFLICT ("customRoleId", entitlement) DO NOTHING;`,
    );
  } else {
    out.push(`DELETE FROM "RoleEntitlement" WHERE "customRoleId" = ${idOf(r.key)};`);
  }
  return out.join("\n\n");
}

export function generate(): string {
  const header = `-- ─────────────────────────────────────────────────────────────────────────────
-- STARTER ROLES, BROUGHT UP TO CURRENT POLICY.
--
-- GENERATED by scripts/generate-starter-roles-migration.ts from
-- ALL_STARTER_ROLES in scripts/install-starter-roles.ts. Do not hand-edit:
-- regenerate it. The previous conversion migration hand-copied that set and
-- the two drifted apart — by the time anyone compared, six of eight roles
-- disagreed and Super was short twelve capabilities.
--
-- WHY A MIGRATION AND NOT THE SCRIPT. The script does the same work, but it
-- is a second command somebody has to remember during a cutover. As a
-- migration it runs unattended with the rest of the chain, fails the deploy
-- loudly if it cannot complete, and leaves a version record of what the
-- database was given.
--
-- The script remains the way to apply policy changes AFTER this. This is a
-- one-time catch-up for a database many revisions behind.
--
-- SAFE TO RE-RUN. Every statement is an upsert or a scoped replace. It
-- never deletes a role, never touches a user's grant, and never overwrites
-- a Setting that already exists — so a role an operator created themselves
-- is untouched, and so is a role of ours they renamed.
-- ─────────────────────────────────────────────────────────────────────────────`;

  const body = ALL_STARTER_ROLES.map(roleSql).join("\n\n");

  // The default role for approving a staff sign-up. It holds an ID, so it
  // can only be written once the roles above exist. Created only if absent:
  // an operator who pointed it somewhere else chose that.
  const setting = `-- ── The role a new staff sign-up is granted on approval ──
-- Created only when absent. If an operator has pointed it at a different
-- role, that is their decision and this leaves it alone.
--
-- SUPPLY THE ID. \`Setting.id\` is \`@default(cuid())\`, which Prisma
-- generates in the CLIENT — the column has no database default, so raw SQL
-- that omits it inserts NULL and fails the not-null constraint. This
-- statement shipped without an id and broke the production deploy: dev
-- already had the row, so only the no-op path was ever exercised. Every
-- other insert in this file uses the same \`gen_random_uuid()::text\`.
INSERT INTO "Setting" (id, key, value, description, section, "updatedAt")
SELECT gen_random_uuid()::text,
       'STAFF_DEFAULT_ROLE_ID',
       ${idOf("seedlings.worker")},
       'The role granted when a pending sign-up is approved as staff. Set it to whichever role your new hires should start with; clear it to approve without granting anything.',
       'catalogs',
       now()
 WHERE ${idOf("seedlings.worker")} IS NOT NULL
   AND NOT EXISTS (SELECT 1 FROM "Setting" WHERE key = 'STAFF_DEFAULT_ROLE_ID');`;

  // A FLOOR, NOT A CEREMONY. If the chain somehow leaves nobody holding
  // the top rung, that is a locked-out owner and the deploy should fail
  // here rather than after everyone has gone home.
  const guard = `-- ── Refuse to finish if this would leave nobody able to administer ──
DO $$
DECLARE supers int;
BEGIN
  SELECT count(*) INTO supers
    FROM "UserCustomRole" g
    JOIN "CustomRole" r ON r.id = g."customRoleId"
   WHERE r.key = 'seedlings.super';
  IF supers = 0 THEN
    RAISE EXCEPTION
      'No user holds seedlings.super after the starter-role catch-up. Refusing to leave the database with nobody able to administer it.';
  END IF;
END $$;`;

  return [header, body, setting, guard].join("\n\n") + "\n";
}

if (require.main === module) {
  const sql = generate();
  if (process.argv.includes("--write")) {
    const name = process.argv[process.argv.indexOf("--write") + 1] ?? "20261027090000_starter_roles_to_current_policy";
    const dir = join(__dirname, "..", "prisma", "migrations", name);
    mkdirSync(dir, { recursive: true });
    writeFileSync(join(dir, "migration.sql"), sql);
    console.log(`wrote prisma/migrations/${name}/migration.sql  (${sql.split("\n").length} lines)`);
  } else {
    process.stdout.write(sql);
  }
}
